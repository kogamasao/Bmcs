/*
 * チーム作成・チーム情報変更のヘルプに「公開する範囲」の説明を追加する（issues.md P-12）
 *
 * 背景：公開範囲（選手名を背番号で表示する・代表者名を表示しない）を選べるようにしたため、ヘルプに説明を加える。
 * 本文は DbInitializer.cs（新規DBの初期データ）と同じ内容になる。
 * 対象：5 チーム作成、6 チーム情報変更
 * 20260924_help_screens.sql の後に実行する。本文に「公開する範囲」が既にある場合は変更しないため、再実行しても安全。GO は使用していない。
 */

--------------------------------------------------------------------------------
-- 1) 変更前の内容を退避する（戻せるようにしておく）
--------------------------------------------------------------------------------
IF OBJECT_ID('dbo.SystemAdminBackup_20260926b') IS NULL
BEGIN
    SELECT SystemAdminClass
         , MessageTitle
         , MessageDetail
         , BackupDatetime = SYSDATETIME()
      INTO dbo.SystemAdminBackup_20260926b
      FROM dbo.SystemAdmin
     WHERE SystemAdminClass IN (5, 6);
END;

--------------------------------------------------------------------------------
-- 2) 追記
--------------------------------------------------------------------------------
UPDATE dbo.SystemAdmin
   SET MessageDetail = REPLACE(REPLACE(MessageDetail
                             , N'非公開の場合、他チームとのメッセージのやり取りはできません。あとから変更できます。</li>'
                             , N'非公開の場合、他チームとのメッセージのやり取りはできません。あとから変更できます。</li><li>公開する範囲<br>公開したときの、他のチームやログインしていない人への見え方を選びます。選手名は「氏名を表示する」か「背番号で表示する」（メンバーのメッセージも表示しません）、代表者名は「表示する」か「表示しない」を選べます。自チームのユーザには、いつも氏名で表示されます。</li>')
                             , N'メールアドレス以外は、公開チームにした場合に誰でも見られます。'
                             , N'メールアドレス以外は、公開チームにした場合に誰でも見られます（代表者名は「公開する範囲」で表示しないこともできます）。')
     , UpdateDatetime = SYSDATETIME()
 WHERE SystemAdminClass IN (5, 6)
   AND MessageDetail NOT LIKE N'%公開する範囲%';

--------------------------------------------------------------------------------
-- 3) 確認（どちらも 1 になっていること。0 の場合は本文が想定と違うため、個別に確認する）
--------------------------------------------------------------------------------
SELECT SystemAdminClass
     , 公開する範囲の説明あり = CASE WHEN MessageDetail LIKE N'%公開する範囲%' THEN 1 ELSE 0 END
  FROM dbo.SystemAdmin
 WHERE SystemAdminClass IN (5, 6);
