END;

--------------------------------------------------------------------------------
-- 2) 書き換え
--------------------------------------------------------------------------------
-- A-1 以前の版の本SQL（「公開する範囲」の説明が短い版）を実行済みの場合は、説明を新しい文言に置き換える
UPDATE dbo.SystemAdmin
   SET MessageDetail = REPLACE(MessageDetail, N'<li>公開する範囲<br>公開したときの、他のチームやログインしていない人への見え方を選びます。選手名は「氏名を表示する」か「背番号で表示する」（メンバーのメッセージも表示しません）、代表者名は「表示する」か「表示しない」を選べます。自チームのユーザには、いつも氏名で表示されます。</li>', N'<li>公開する範囲<br>公開したときの、他のチームやログインしていない人への見え方を選びます。選手名は「氏名を表示する」か「背番号で表示する」（メンバーのメッセージとイニング詳細の備考も表示しません）、代表者名は「表示する」か「表示しない」を選べます。自チームのユーザには、いつも氏名で表示されます。チーム紹介など、チームで書き込む欄の内容はそのまま表示されます。</li>')
     , UpdateDatetime = SYSDATETIME()
 WHERE SystemAdminClass IN (5, 6)
   AND MessageDetail LIKE N'%<li>公開する範囲<br>公開したときの、他のチームやログインしていない人への見え方を選びます。選手名は「氏名を表示する」か「背番号で表示する」（メンバーのメッセージも表示しません）、代表者名は「表示する」か「表示しない」を選べます。自チームのユーザには、いつも氏名で表示されます。</li>%';

-- A-2 「公開する範囲」の項目を追加する
UPDATE dbo.SystemAdmin
   SET MessageDetail = REPLACE(MessageDetail, N'非公開の場合、他チームとのメッセージのやり取りはできません。あとから変更できます。</li>', N'非公開の場合、他チームとのメッセージのやり取りはできません。あとから変更できます。</li><li>公開する範囲<br>公開したときの、他のチームやログインしていない人への見え方を選びます。選手名は「氏名を表示する」か「背番号で表示する」（メンバーのメッセージとイニング詳細の備考も表示しません）、代表者名は「表示する」か「表示しない」を選べます。自チームのユーザには、いつも氏名で表示されます。チーム紹介など、チームで書き込む欄の内容はそのまま表示されます。</li>')
     , UpdateDatetime = SYSDATETIME()
 WHERE SystemAdminClass IN (5, 6)
   AND MessageDetail LIKE N'%非公開の場合、他チームとのメッセージのやり取りはできません。あとから変更できます。</li>%'
   AND MessageDetail NOT LIKE N'%<li>公開する範囲<br>%';

-- B 代表者名の注記を添える
UPDATE dbo.SystemAdmin
   SET MessageDetail = REPLACE(MessageDetail, N'メールアドレス以外は、公開チームにした場合に誰でも見られます。', N'メールアドレス以外は、公開チームにした場合に誰でも見られます（代表者名は「公開する範囲」で表示しないこともできます）。')
     , UpdateDatetime = SYSDATETIME()
 WHERE SystemAdminClass IN (5, 6)
   AND MessageDetail LIKE N'%メールアドレス以外は、公開チームにした場合に誰でも見られます。%';

-- C 「チーム情報（…）」から「代表者名」を外す
UPDATE dbo.SystemAdmin
   SET MessageDetail = REPLACE(MessageDetail, N'チーム情報（代表者名・活動拠点・チーム紹介など）を', N'チーム情報（活動拠点・チーム紹介など）を')
     , UpdateDatetime = SYSDATETIME()
 WHERE SystemAdminClass IN (5, 6)
   AND MessageDetail LIKE N'%チーム情報（代表者名・活動拠点・チーム紹介など）を%';

