/*
 * チーム作成・チーム情報変更のヘルプに「公開する範囲」の説明を追加する（issues.md P-12）
 *
 * 背景：公開範囲（選手名を背番号で表示する・代表者名を表示しない）を選べるようにしたため、ヘルプを合わせる。
 * 本文は DbInitializer.cs（新規DBの初期データ）と同じ内容になる。
 * 対象：5 チーム作成、6 チーム情報変更。20260924_help_screens.sql の後に実行する。
 *
 * 書き換えは3つあり、それぞれ別に判定する（1つの書き換えが当たらなくても、他の書き換えや確認に影響しないように）。
 *   A 「チームを公開する」の項目の後ろに「公開する範囲」の項目を追加する
 *   B 任意項目の説明に「代表者名は「公開する範囲」で表示しないこともできます」を添える
 *   C 「チーム情報（代表者名・活動拠点・チーム紹介など）」から「代表者名」を外す
 * どれも書き換え前の文言がある場合だけ書き換えるため、再実行しても安全。GO は使用していない。
 *
 * 手順：
 *   1) 実行前の確認で、5・6 とも「追加する場所あり」「代表者名の注記_前」「チーム情報の文言_前」が 1 であることを確かめる。
 *      0 の項目がある場合は本文が想定と違う（手で変更された等）ため、その書き換えは行われない。本文を確認して個別に直す。
 *   2) 実行後の確認で、「範囲の説明あり」「代表者名の注記_後」「チーム情報の文言_後」が 1 になっていることを確かめる。
 */

--------------------------------------------------------------------------------
-- 0) 実行前の確認
--------------------------------------------------------------------------------
SELECT SystemAdminClass
     , 追加する場所あり = CASE WHEN MessageDetail LIKE N'%非公開の場合、他チームとのメッセージのやり取りはできません。あとから変更できます。</li>%' THEN 1 ELSE 0 END
     , 範囲の説明あり = CASE WHEN MessageDetail LIKE N'%<li>公開する範囲<br>公開したときの、他のチームやログインしていない人への見え方を選びます。選手名は「氏名を表示する」か「背番号で表示する」（メンバーのメッセージとイニング詳細の備考も表示しません）、代表者名は「表示する」か「表示しない」を選べます。自チームのユーザには、いつも氏名で表示されます。チーム紹介など、チームで書き込む欄の内容はそのまま表示されます。</li>%' THEN 1 ELSE 0 END
     , 代表者名の注記_前 = CASE WHEN MessageDetail LIKE N'%メールアドレス以外は、公開チームにした場合に誰でも見られます。%' THEN 1 ELSE 0 END
     , 代表者名の注記_後 = CASE WHEN MessageDetail LIKE N'%メールアドレス以外は、公開チームにした場合に誰でも見られます（代表者名は「公開する範囲」で表示しないこともできます）。%' THEN 1 ELSE 0 END
     , チーム情報の文言_前 = CASE WHEN MessageDetail LIKE N'%チーム情報（代表者名・活動拠点・チーム紹介など）を%' THEN 1 ELSE 0 END
     , チーム情報の文言_後 = CASE WHEN MessageDetail LIKE N'%チーム情報（活動拠点・チーム紹介など）を%' THEN 1 ELSE 0 END
  FROM dbo.SystemAdmin
 WHERE SystemAdminClass IN (5, 6);

--------------------------------------------------------------------------------
-- 1) 変更前の内容を退避する（戻せるようにしておく）
--------------------------------------------------------------------------------
IF OBJECT_ID('dbo.SystemAdminBackup_20260926b') IS NULL
BEGIN
    SELECT SystemAdminClass
         , MessageTitle
         , MessageDetail
         , BackupDatetime = SYSDATETIME()
      INTO dbo.SystemAdminBackup_20260926b
      FROM dbo.SystemAdmin
